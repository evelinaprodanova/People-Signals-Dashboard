// Packs demo-data/*.csv and templates/*.csv into src/demo.js so index.html also works when opened from disk
// (a browser will not let a page read local files by itself). Run: node scripts/build-demo.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const read = dir => Object.fromEntries(fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith('.csv'))
  .map(f => [f.replace(/\.csv$/, ''), fs.readFileSync(path.join(root, dir, f), 'utf8')]));
const out = '/* Generated by scripts/build-demo.js. Do not edit by hand: edit demo-data/ or templates/ and run the script. */\n' +
  'window.PS_DEMO = ' + JSON.stringify(read('demo-data')) + ';\nwindow.PS_TEMPLATES = ' + JSON.stringify(read('templates')) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'demo.js'), out);
console.log('wrote src/demo.js', out.length, 'bytes');
